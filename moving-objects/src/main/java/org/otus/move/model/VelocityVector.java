package org.otus.move.model;

public class VelocityVector {

    private double x;
    private double y;

    public VelocityVector( double x, double y ) {
        this.x = x;
        this.y = y;
    }

    public double getX( ) {
        return x;
    }

    public double getY( ) {
        return y;
    }

}
